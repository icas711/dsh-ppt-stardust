export function resolveLanguage(input) {
  const id = String(input ?? 'zh').trim().toLowerCase()
  const language = LANGUAGES[id]
  if (!language) {
    throw new Error('dsh-ppt：未知语言 "' + id + '"，可选：zh / en / bilingual / ru')
  }
  return language
}
